class SelfImprove(BaseModule):
    """Give JARVIS the ability to extend and rewrite himself."""

    name = "self_improve"
    description = (
        "Self-extension and self-modification: search GitHub for projects, integrate a "
        "repository as a new skill, inspect and rewrite JARVIS's own source code, run his "
        "test suite, hot-reload modules, and roll changes back."
    )
    intent_examples = [
        "search github for a python music player library",
        "integrate that repository into yourself",
        "add a new skill for controlling spotify",
        "improve your own weather tool",
        "show me your own source code",
        "run your tests",
        "undo your last change",
    ]

    def __init__(self, config: Any, llm: Any = None, security: Any = None) -> None:
        """Read the ``self_improve`` configuration and prepare bookkeeping."""
        super().__init__(config, llm=llm, security=security)
        section = config.section("self_improve")
        self.enabled: bool = bool(section.get("enabled", True))
        self.allow_code_edit: bool = bool(section.get("allow_code_edit", True))
        self.allow_plugin_install: bool = bool(section.get("allow_plugin_install", True))
        self.allow_pip_install: bool = bool(section.get("allow_pip_install", False))
        self.run_tests: bool = bool(section.get("run_tests_after_edit", True))
        self.test_command: str = str(section.get("test_command", "tests/test_smoke.py"))
        self.test_timeout: float = float(section.get("test_timeout", 900))
        self.git_commit_enabled: bool = bool(section.get("git_commit", True))
        self.auto_reload: bool = bool(section.get("auto_reload", True))
        self.max_file_bytes: int = int(section.get("max_file_bytes", 400_000))
        self.max_results: int = int(section.get("max_search_results", 8))
        self.token_env: str = str(section.get("github_token_env", "GITHUB_TOKEN"))
        self.keep_backups: int = int(section.get("keep_backups", 40))

        self.root: Path = Path(getattr(config, "root", Path.cwd()))
        self.plugins_dir: Path = config.resolve(section.get("plugins_dir", "plugins"))
        self.repos_dir: Path = config.resolve(section.get("repos_dir", "data/repos"))
        self.backup_dir: Path = config.resolve(section.get("backup_dir", "data/backups"))
        self.protected: List[str] = list(
            dict.fromkeys(
                [str(item) for item in (section.get("protected") or [])]
                + sorted(ALWAYS_PROTECTED)
            )
        )
        self.db_path: Path = config.resolve(config.get("database.path", "data/jarvis.db"))

        #: Set by :class:`core.brain.Brain` so new skills can be registered live.
        self.brain: Optional[Any] = None
        self._init_db()

    # ------------------------------------------------------------------ infra
    async def setup(self) -> None:
        """Make sure the plugin, repo and backup directories exist."""
        for directory in (self.plugins_dir, self.repos_dir, self.backup_dir):
            try:
                ensure_dir(directory)
            except Exception as exc:
                self.log.debug("Could not create %s: %s", directory, exc)
        readme = self.plugins_dir / "README.md"
        if not readme.exists():
            try:
                readme.write_text(
                    "# Plugins\n\nEvery `.py` file here that defines a `BaseModule` "
                    "subclass is loaded as a JARVIS skill at start-up.\n"
                    "Files in this folder are generated by the `self_improve` module — "
                    "read them before trusting them.\n",
                    encoding="utf-8",
                )
            except Exception:
                pass

    def _connect(self) -> sqlite3.Connection:
        """Open the shared SQLite database."""
        ensure_dir(self.db_path.parent)
        connection = sqlite3.connect(str(self.db_path), timeout=30)
        connection.row_factory = sqlite3.Row
        return connection

    def _init_db(self) -> None:
        """Create the change-log table."""
        try:
            with self._connect() as connection:
                connection.executescript(
                    """
                    CREATE TABLE IF NOT EXISTS self_changes (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        created_at TEXT NOT NULL,
                        kind TEXT NOT NULL,
                        target TEXT NOT NULL,
                        description TEXT,
                        backup TEXT,
                        tests TEXT,
                        committed TEXT,
                        reverted INTEGER DEFAULT 0
                    );
                    CREATE INDEX IF NOT EXISTS idx_changes_target ON self_changes(target);
                    """
                )
        except Exception as exc:
            self.log.debug("Change log init failed: %s", exc)

    def _record(
        self,
        kind: str,
        target: str,
        description: str,
        backup: str = "",
        tests: str = "",
        committed: str = "",
    ) -> int:
        """Write a row into the change log and return its id."""
        try:
            with self._connect() as connection:
                cursor = connection.execute(
                    "INSERT INTO self_changes"
                    " (created_at, kind, target, description, backup, tests, committed)"
                    " VALUES (?, ?, ?, ?, ?, ?, ?)",
                    (
                        datetime.now().isoformat(timespec="seconds"),
                        kind,
                        target,
                        truncate(description, 500),
                        backup,
                        tests,
                        committed,
                    ),
                )
                return int(cursor.lastrowid or 0)
        except Exception as exc:
            self.log.debug("Could not record change: %s", exc)
            return 0

    # ---------------------------------------------------------- offline route
    def offline_router(self, command: str) -> Optional[tuple[str, Dict[str, Any]]]:
        """Rule-based routing used when no LLM is available."""
        text = strip_command_prefix(command)
        lowered = text.lower()

        if "github" in lowered and any(
            word in lowered for word in ("search", "find", "look for", "look up")
        ):
            query = re.sub(
                r".*?(?:search|find|look for|look up)\s+(?:github\s+)?(?:for\s+)?", "", lowered
            ).replace("on github", "").strip()
            return "search_github", {"query": query or text}
        if "integrate" in lowered or "install the repo" in lowered or "add the repo" in lowered:
            match = re.search(r"[\w.-]+/[\w.-]+", text)
            return "integrate_repo", {"repo": match.group(0) if match else text}
        if "plugin" in lowered and any(w in lowered for w in ("list", "what", "show")):
            return "list_plugins", {}
        if "plugin" in lowered and any(w in lowered for w in ("remove", "delete", "uninstall")):
            match = re.search(r"(?:remove|delete|uninstall)\s+(?:the\s+)?(\w+)", lowered)
            return "remove_plugin", {"name": match.group(1) if match else text}
        if any(word in lowered for word in ("run your test", "self test", "test yourself",
                                            "run the tests")):
            return "run_self_tests", {}
        if any(word in lowered for word in ("undo", "roll back", "rollback", "revert")):
            return "rollback", {}
        if ("history" in lowered and ("change" in lowered or "edit" in lowered)) or any(
            phrase in lowered
            for phrase in ("what have you changed", "what did you change",
                           "changed about yourself", "your changes", "change log",
                           "changelog")
        ):
            return "change_history", {}
        if any(phrase in lowered for phrase in ("what can you do to yourself",
                                                "self improvement status",
                                                "self-improvement status")):
            return "self_status", {}
        if "suggest" in lowered or "what would you improve" in lowered:
            return "suggest_improvements", {"focus": text}
        if any(word in lowered for word in ("your code", "your source", "own code",
                                            "source code")):
            match = re.search(r"[\w/]+\.py", text)
            if match:
                return "read_own_code", {"path": match.group(0)}
            return "code_map", {}
        if "reload" in lowered:
            match = re.search(r"reload\s+(?:the\s+)?(\w+)", lowered)
            return "reload_module", {"name": match.group(1) if match else ""}
        if any(word in lowered for word in ("improve", "modify", "rewrite", "fix your",
                                            "change your", "edit your", "upgrade your")):
            match = re.search(r"[\w/]+\.py", text)
            return "edit_own_code", {"path": match.group(0) if match else "",
                                     "instruction": text}
        return "code_map", {}

    # ---------------------------------------------------------------- GitHub
    async def _github(self, path: str, params: Optional[Dict[str, Any]] = None,
                      raw: bool = False) -> Optional[Any]:
        """Call the public GitHub API. Returns parsed JSON, text, or ``None``."""
        try:
            import httpx
        except Exception:
            return None

        headers = {
            "Accept": "application/vnd.github.raw" if raw else "application/vnd.github+json",
            "User-Agent": "JARVIS-local-assistant",
            "X-GitHub-Api-Version": "2022-11-28",
        }
        token = os.environ.get(self.token_env, "").strip()
        if token:
            headers["Authorization"] = f"Bearer {token}"
        try:
            async with httpx.AsyncClient(
                timeout=25, follow_redirects=True, verify=ssl_verify()
            ) as client:
                response = await client.get(
                    f"{GITHUB_API}{path}", params=params or {}, headers=headers
                )
                if response.status_code == 403 and "rate limit" in response.text.lower():
                    self.log.warning("GitHub rate limit reached.")
                    return {"__error__": "rate_limit"}
                response.raise_for_status()
                return response.text if raw else response.json()
        except Exception as exc:
            self.log.debug("GitHub request failed: %s", truncate(str(exc), 160))
            return None

    @tool(
        description="Search GitHub for repositories (no API key needed).",
        params={
            "query": {"type": "string", "description": "What to look for", "required": True},
            "language": {"type": "string", "description": "Filter by language",
                         "default": "python"},
            "min_stars": {"type": "integer", "description": "Minimum stars", "default": 25},
            "limit": {"type": "integer", "description": "How many results", "default": 8},
        },
        keywords=["search github", "find a repo", "github for", "is there a library",
                  "open source project for", "find a package"],
        examples=['search_github(query="home assistant control", min_stars=100)'],
    )
    async def search_github(
        self, query: str, language: str = "python", min_stars: int = 25, limit: int = 8
    ) -> ModuleResult:
        """Search public repositories, sorted by stars."""
        query = (query or "").strip()
        if not query:
            return ModuleResult.fail("What should I look for on GitHub, sir?")

        terms = [query]
        if language:
            terms.append(f"language:{language}")
        if min_stars:
            terms.append(f"stars:>={int(min_stars)}")
        payload = await self._github(
            "/search/repositories",
            {
                "q": " ".join(terms),
                "sort": "stars",
                "order": "desc",
                "per_page": max(1, min(int(limit or self.max_results), 20)),
            },
        )
        if payload is None:
            return ModuleResult.fail(
                "GitHub is unreachable — check the network. (No key is needed for search; "
                f"set ${self.token_env} only if you hit the rate limit.)"
            )
        if isinstance(payload, dict) and payload.get("__error__") == "rate_limit":
            return ModuleResult.fail(
                f"GitHub's anonymous rate limit is exhausted. Export a free personal token "
                f"as ${self.token_env} and I'll get 30 searches a minute instead of 10."
            )

        items = (payload or {}).get("items", []) if isinstance(payload, dict) else []
        if not items:
            return ModuleResult.ok(f"Nothing on GitHub matches '{query}'.", results=[])

        results: List[Dict[str, Any]] = []
        lines: List[str] = []
        for index, item in enumerate(items, 1):
            licence = ((item.get("license") or {}).get("spdx_id") or "no licence")
            entry = {
                "repo": item.get("full_name", ""),
                "description": truncate(item.get("description") or "", 180),
                "stars": int(item.get("stargazers_count", 0)),
                "language": item.get("language") or "",
                "license": licence,
                "url": item.get("html_url", ""),
                "clone_url": item.get("clone_url", ""),
                "updated": (item.get("pushed_at") or "")[:10],
                "topics": item.get("topics", [])[:5],
            }
            results.append(entry)
            lines.append(
                f"{index}. {entry['repo']} ★{entry['stars']:,} · {entry['language']} · "
                f"{entry['license']} · updated {entry['updated']}\n"
                f"   {entry['description']}\n   {entry['url']}"
            )

        top = results[0]
        return ModuleResult(
            success=True,
            output=f"GitHub results for '{query}':\n" + "\n".join(lines),
            speak=f"The strongest candidate is {top['repo']} with "
                  f"{top['stars']:,} stars. {top['description']}",
            data={"results": results, "query": query},
        ).offering(
            "self_improve.integrate_repo",
            {"repo": top["repo"]},
            f"Shall I integrate {top['repo']} into myself?",
        )

    @tool(
        description="Show details and the README of a GitHub repository.",
        params={
            "repo": {"type": "string", "description": "owner/name", "required": True},
        },
        keywords=["tell me about the repo", "repo details", "what does that project do",
                  "show me the readme"],
    )
    async def repo_details(self, repo: str) -> ModuleResult:
        """Fetch metadata plus a trimmed README for a repository."""
        slug = self._normalise_repo(repo)
        if not slug:
            return ModuleResult.fail("Give me the repository as 'owner/name', sir.")
        meta = await self._github(f"/repos/{slug}")
        if not isinstance(meta, dict) or meta.get("__error__"):
            return ModuleResult.fail(f"Could not read {slug} from GitHub.")
        readme = await self._github(f"/repos/{slug}/readme", raw=True)
        summary = (
            f"{meta.get('full_name')} — {meta.get('description') or 'no description'}\n"
            f"★ {meta.get('stargazers_count', 0):,} · forks {meta.get('forks_count', 0):,} · "
            f"{meta.get('language') or 'mixed'} · "
            f"{((meta.get('license') or {}).get('spdx_id') or 'no licence')} · "
            f"updated {(meta.get('pushed_at') or '')[:10]}\n{meta.get('html_url')}"
        )
        if isinstance(readme, str) and readme.strip():
            summary += "\n\nREADME (trimmed):\n" + truncate(readme.strip(), 2000)
        return ModuleResult(
            success=True,
            output=summary,
            speak=f"{slug}: {truncate(meta.get('description') or '', 200)}",
            data={"repo": slug, "meta": {
                "stars": meta.get("stargazers_count", 0),
                "license": (meta.get("license") or {}).get("spdx_id", ""),
                "clone_url": meta.get("clone_url", ""),
                "default_branch": meta.get("default_branch", "main"),
            }},
        ).offering(
            "self_improve.integrate_repo", {"repo": slug},
            f"Shall I integrate {slug}?",
        )

    @staticmethod
    def _normalise_repo(repo: str) -> str:
        """Turn a URL or free text into ``owner/name``."""
        text = (repo or "").strip().rstrip("/")
        match = re.search(r"github\.com[:/]+([\w.-]+/[\w.-]+?)(?:\.git)?$", text)
        if match:
            return match.group(1)
        match = re.search(r"^([\w.-]+/[\w.-]+?)(?:\.git)?$", text)
        if match:
            return match.group(1)
        match = re.search(r"([\w.-]+/[\w.-]+)", text)
        return match.group(1) if match else ""

    # ------------------------------------------------------------ integration
    @tool(
        description=(
            "Clone a GitHub repository and write a JARVIS skill adapter for it, making its "
            "functionality available as new tools."
        ),
        params={
            "repo": {"type": "string", "description": "owner/name, URL or local path",
                     "required": True},
            "name": {"type": "string", "description": "Skill name (default: repo name)",
                     "default": ""},
            "goal": {"type": "string",
                     "description": "What the new skill should let JARVIS do", "default": ""},
            "pip_install": {"type": "boolean",
                            "description": "Also pip install the repo's requirements",
                            "default": False},
        },
        dangerous=True,
        keywords=["integrate that repo", "add that project", "install that plugin",
                  "make that a skill", "absorb that repository", "learn that library"],
        examples=['integrate_repo(repo="psf/requests-html", goal="scrape javascript pages")'],
    )
    async def integrate_repo(
        self, repo: str, name: str = "", goal: str = "", pip_install: bool = False
    ) -> ModuleResult:
        """Clone a repository and generate, validate and register a skill adapter."""
        if not self.allow_plugin_install:
            return ModuleResult.fail(
                "Plugin installation is disabled — set self_improve.allow_plugin_install: "
                "true in config.yaml if you trust me with it."
            )

        source = (repo or "").strip()
        local_source = Path(source).expanduser()
        is_local = local_source.exists()
        slug_source = local_source.name if is_local else self._normalise_repo(source)
        if not slug_source:
            return ModuleResult.fail("I need a repository as 'owner/name' or a URL, sir.")

        skill = slugify(name or slug_source.split("/")[-1], 40).replace("-", "_").strip("_")
        skill = re.sub(r"[^a-z0-9_]", "", skill.lower()) or "skill"
        if skill in {"base", "self_improve"} or (self.brain and skill in
                                                 getattr(self.brain, "modules", {})):
            skill = f"{skill}_skill"

        clone_url = str(local_source) if is_local else f"https://github.com/{slug_source}.git"
        destination = self.repos_dir / skill

        def _clone() -> Tuple[bool, str]:
            """Shallow-clone the repository, refreshing an existing copy."""
            try:
                ensure_dir(self.repos_dir)
                if destination.exists():
                    shutil.rmtree(destination, ignore_errors=True)
                completed = subprocess.run(
                    ["git", "clone", "--depth", "1", clone_url, str(destination)],
                    capture_output=True, text=True, timeout=300,
                )
                if completed.returncode != 0:
                    return False, (completed.stderr or completed.stdout)[-400:]
                return True, ""
            except FileNotFoundError:
                return False, "git is not installed — install it and try again."
            except Exception as exc:
                return False, str(exc)

        cloned, error = await run_blocking(_clone)
        if not cloned:
            return ModuleResult.fail(f"Clone failed: {truncate(error, 300)}")

        survey = await run_blocking(self._survey_repo, destination)
        installed = ""
        if pip_install:
            result = await self.install_package(
                package=str(destination), from_path=True
            )
            installed = result.output

        adapter = await self._write_adapter(skill, slug_source, destination, survey, goal)
        if not adapter.success:
            return adapter

        registered = await self._register_plugin(skill, adapter.data.get("path", ""))
        self._record(
            "plugin",
            skill,
            f"Integrated {slug_source} ({survey['files']} files)",
            backup="",
            tests="",
            committed=await self._git_commit(
                [adapter.data.get("path", "")], f"self: integrate {slug_source} as {skill}"
            ),
        )
        tools = ", ".join(registered.get("tools", [])) or "about"
        note = f"\n{installed}" if installed else ""
        return ModuleResult(
            success=True,
            output=(
                f"Integrated {slug_source} as the '{skill}' skill.\n"
                f"  source : {destination}\n"
                f"  adapter: {adapter.data.get('path')}\n"
                f"  tools  : {tools}\n"
                f"  status : {registered.get('status')}"
                f"{note}"
            ),
            speak=f"{slug_source} is now part of me, sir. New skill '{skill}' with "
                  f"{len(registered.get('tools', []))} tools.",
            data={"skill": skill, "repo": slug_source, "tools": registered.get("tools", []),
                  "adapter": adapter.data.get("path", "")},
        )

    def _survey_repo(self, path: Path) -> Dict[str, Any]:
        """Collect the facts the LLM needs to write an adapter."""
        info: Dict[str, Any] = {
            "readme": "", "files": 0, "python_files": [], "package": "",
            "entry_points": [], "requirements": [], "size": 0,
        }
        try:
            for candidate in ("README.md", "README.rst", "README.txt", "readme.md"):
                readme = path / candidate
                if readme.exists():
                    info["readme"] = truncate(
                        readme.read_text(encoding="utf-8", errors="replace"), 4000
                    )
                    break

            python_files: List[Tuple[int, Path]] = []
            for file in path.rglob("*.py"):
                if any(part in {".git", "test", "tests", "docs", "examples", "build"}
                       for part in file.parts):
                    continue
                try:
                    size = file.stat().st_size
                except Exception:
                    continue
                info["files"] += 1
                info["size"] += size
                python_files.append((size, file))
            python_files.sort(reverse=True)
            info["python_files"] = [
                str(file.relative_to(path)) for _, file in python_files[:20]
            ]

            for meta_name in ("pyproject.toml", "setup.py", "setup.cfg"):
                meta = path / meta_name
                if not meta.exists():
                    continue
                text = meta.read_text(encoding="utf-8", errors="replace")
                match = re.search(r'name\s*=\s*["\']([\w.-]+)["\']', text)
                if match:
                    info["package"] = match.group(1)
                    break
            if not info["package"]:
                for child in path.iterdir():
                    if child.is_dir() and (child / "__init__.py").exists():
                        info["package"] = child.name
                        break

            requirements = path / "requirements.txt"
            if requirements.exists():
                info["requirements"] = [
                    line.strip()
                    for line in requirements.read_text(
                        encoding="utf-8", errors="replace"
                    ).splitlines()[:25]
                    if line.strip() and not line.startswith("#")
                ]

            # Public functions of the package's __init__ or the biggest module.
            probe = None
            if info["package"]:
                candidate = path / info["package"] / "__init__.py"
                probe = candidate if candidate.exists() else None
            if probe is None and python_files:
                probe = python_files[0][1]
            if probe is not None:
                try:
                    tree = ast.parse(probe.read_text(encoding="utf-8", errors="replace"))
                    for node in tree.body:
                        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef,
                                             ast.ClassDef)) and not node.name.startswith("_"):
                            signature = node.name
                            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                                args = [a.arg for a in node.args.args if a.arg != "self"]
                                signature = f"{node.name}({', '.join(args)})"
                            doc = (ast.get_docstring(node) or "").split("\n")[0]
                            info["entry_points"].append(
                                f"{signature} — {truncate(doc, 100)}" if doc else signature
                            )
                except Exception:
                    pass
                info["entry_points"] = info["entry_points"][:20]
        except Exception as exc:
            self.log.debug("Repo survey failed: %s", exc)
        return info

    async def _write_adapter(
        self, skill: str, repo: str, clone: Path, survey: Dict[str, Any], goal: str
    ) -> ModuleResult:
        """Ask the LLM for an adapter module, validate it, and write it to disk."""
        classname = "".join(part.title() for part in skill.split("_")) or "Skill"
        target = self.plugins_dir / f"{skill}.py"
        ensure_dir(self.plugins_dir)

        fallback = ADAPTER_TEMPLATE.format(
            slug=skill,
            classname=classname,
            repo=repo,
            url=f"https://github.com/{repo}",
            clone=clone,
            stamp=datetime.now().strftime("%Y-%m-%d %H:%M"),
            description=f"Skill generated from the {repo} repository.",
            examples=[f"use {skill}"],
            keywords=[skill, repo.split("/")[-1].lower()],
        )

        if self.llm is None or not getattr(self.llm, "available", False):
            await run_blocking(target.write_text, fallback, "utf-8")
            return ModuleResult(
                success=True,
                output=f"Wrote a stub adapter (no LLM available) to {target}.",
                data={"path": str(target), "generated": False},
            )

        prompt = self._adapter_prompt(skill, classname, repo, clone, survey, goal)
        code = ""
        error = ""
        for attempt in range(1, 3):
            raw = await self.llm.complete(
                prompt if attempt == 1 else
                f"{prompt}\n\nYour previous attempt failed with:\n{error}\n"
                "Return the corrected COMPLETE file.",
                temperature=0.2,
                max_tokens=2200,
            )
            candidate = self._extract_python(raw)
            if not candidate:
                error = "no python code block found in the response"
                continue
            ok, error = self._validate_adapter(candidate, skill)
            if ok:
                code = candidate
                break
            self.log.debug("Adapter attempt %d rejected: %s", attempt, error)

        if not code:
            await run_blocking(target.write_text, fallback, "utf-8")
            return ModuleResult(
                success=True,
                output=(
                    f"The generated adapter didn't pass validation ({truncate(error, 160)}), "
                    f"so I wrote a safe stub to {target} instead. The cloned source is at "
                    f"{clone} — ask me to write a wrapper for a specific function."
                ),
                data={"path": str(target), "generated": False, "error": error},
            )

        header = (
            f"# /plugins/{skill}.py\n"
            f"# Generated by JARVIS self_improve on "
            f"{datetime.now():%Y-%m-%d %H:%M} from {repo}\n"
            f"# Upstream: https://github.com/{repo}\n"
            f"# Local clone: {clone}\n"
        )
        if not code.startswith("#"):
            code = header + code
        await run_blocking(target.write_text, code, "utf-8")
        return ModuleResult(
            success=True,
            output=f"Adapter written to {target}.",
            data={"path": str(target), "generated": True},
        )

