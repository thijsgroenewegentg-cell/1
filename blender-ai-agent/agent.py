def connect_with_help(host, port):
    try:
        bridge = BlenderBridge(host, port)
    except (ConnectionError, OSError) as exc:
        print("Could not connect to Blender at %s:%d (%s)." % (host, port, exc))
        print("Start the bridge first:\n"
              "  - Blender: N-panel > 'AI Agent' tab > 'Start AI Agent Server', or\n"
              "  - run: blender --python bridge_standalone.py")
        sys.exit(1)
    reply = bridge.call("ping")
    if reply.get("ok"):
        info = reply["result"]
        print("Connected to Blender %s (scene: %s)."
              % (info.get("blender"), info.get("scene")))
    return bridge


def build_llm_chain(args):
    """Construct primary + fallback LLM clients."""
    primary = detect_provider(args.provider)
    chain_names = [primary]
    if args.fallback and not args.no_fallback:
        for name in ("ollama", "groq", "gemini"):
            if name != primary and name not in chain_names:
                chain_names.append(name)

    llms = []
    for name in chain_names:
        cfg = PROVIDERS[name]
        if cfg.get("key_env") and not os.environ.get(cfg["key_env"]) and not args.api_key:
            continue  # provider has no key configured; skip silently
        model = args.model if name == primary else None
        base_url = args.base_url if name == primary else None
        llms.append(LLMClient(provider=name, model=model, base_url=base_url,
                              api_key=args.api_key if name == primary else None,
                              vision=args.vision))
    if not llms:
        llms = [LLMClient(provider=primary, vision=args.vision)]
    return llms


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Free AI agent that builds things in Blender.")
    parser.add_argument("task", nargs="?",
                        help="What you want built, e.g. \"a small windmill\". "
                             "Omit for interactive chat mode.")
    parser.add_argument("--provider", default=os.environ.get("LLM_PROVIDER"),
                        choices=sorted(PROVIDERS.keys()),
                        help="LLM provider (default: auto-detect; else ollama).")
    parser.add_argument("--model", default=os.environ.get("LLM_MODEL"),
                        help="Override the model name.")
    parser.add_argument("--base-url", default=os.environ.get("LLM_BASE_URL"),
                        help="Override the API base URL (OpenAI-compatible server).")
    parser.add_argument("--api-key", default=None, help="API key override.")
    parser.add_argument("--vision", action="store_true",
                        help="Enable vision: the agent renders and looks at its "
                             "work (use a vision model, e.g. ollama pull "
                             "llama3.2-vision:11b).")
    parser.add_argument("--no-fallback", action="store_true",
                        help="Do not fall back to other free providers on error.")
    parser.add_argument("--approve", action="store_true",
                        help="Ask before running each piece of Blender code.")
    parser.add_argument("--image", metavar="PATH",
                        help="Reference image the agent should build from (requires --vision).")
    parser.add_argument("--host", default=DEFAULT_HOST)
    parser.add_argument("--port", type=int, default=DEFAULT_PORT)
    parser.add_argument("--max-iters", type=int, default=30)
    parser.add_argument("--exec", metavar="FILE",
                        help="Skip the LLM: run a .py file inside Blender.")
    args = parser.parse_args(argv)

    if args.image and not args.vision:
        args.vision = True  # reference images require a vision-capable model

    bridge = connect_with_help(args.host, args.port)

    if args.exec:
        with open(args.exec, "r", encoding="utf-8") as fh:
            code = fh.read()
        reply = bridge.call("exec", code=code)
        result = reply.get("result") or {}
        if result.get("stdout"):
            print(result["stdout"], end="")
        if result.get("error"):
            print(result["error"], file=sys.stderr)
            sys.exit(1)
        return

    llms = build_llm_chain(args)
    print("LLM chain: %s | vision: %s | approve: %s"
          % (" -> ".join("%s(%s)" % (l.provider, l.model) for l in llms),
             "on" if args.vision else "off",
             "on" if args.approve else "off"))
    if args.vision:
        print("Vision enabled - the agent will render and inspect its work.")

    def loop(task_text, ref_image=None):
        return run_task(task_text, bridge, llms, vision=args.vision,
                        max_iters=args.max_iters, approve=args.approve,
                        reference_image=ref_image)

    try:
        if args.task:
            loop(args.task, args.image)
        else:
            print("\nInteractive mode. Describe what you want built. Commands: "
                  "/scene, /undo, /render, /save, /quit\n")
            while True:
                try:
                    task_text = input("you > ").strip()
                except (EOFError, KeyboardInterrupt):
                    print()
                    break
                if not task_text:
                    continue
                if task_text in ("/quit", "/exit"):
                    break
                if task_text == "/scene":
                    print(json.dumps(bridge.call("scene_info").get("result", {}), indent=2))
                    continue
                if task_text == "/undo":
                    print(bridge.call("undo"))
                    continue
                if task_text == "/render":
                    print(bridge.call("render", filepath=_timestamped("render", "png")))
                    continue
                if task_text == "/save":
                    print(bridge.call("save", filepath=_timestamped("scene", "blend")))
                    continue
                try:
                    loop(task_text)
                except RuntimeError as exc:
                    print("\n[agent error] %s" % exc)
    except RuntimeError as exc:
        print("\n[agent error] %s" % exc)
        if "11434" in str(exc) or "ollama" in str(exc).lower():
            print("\nOllama quick start:\n"
                  "  1. Download Ollama: https://ollama.com\n"
                  "  2. ollama pull qwen2.5-coder:7b"
                  + ("\n     (vision) ollama pull llama3.2-vision:11b" if args.vision else "")
                  + "\n  3. Make sure Ollama is running, then try again.")
        sys.exit(1)
    finally:
        bridge.close()


if __name__ == "__main__":
    main()
