def detect_provider(explicit):
    """Auto-pick a provider from available API keys / a running Ollama."""
    if explicit:
        return explicit
    if os.environ.get("GROQ_API_KEY"):
        return "groq"
    if os.environ.get("GEMINI_API_KEY"):
        return "gemini"
    if os.environ.get("OPENAI_API_KEY"):
        return "openai"
    return "ollama"


class LLMClient:
    def __init__(self, provider="ollama", model=None, base_url=None,
                 api_key=None, vision=False, temperature=0.2, log=print):
        self.provider = provider
        cfg = PROVIDERS[provider]
        self.base_url = (base_url or cfg["base_url"]).rstrip("/")
        self.model = model or (cfg.get("vision_model") if vision else None) or cfg["model"]
        key = api_key
        if not key and cfg.get("key_env"):
            key = os.environ.get(cfg["key_env"], "")
        self.api_key = key or cfg.get("api_key", "")
        self.vision = vision
        self.temperature = temperature
        self.hint = cfg.get("hint", "")
        self.log = log

    def chat(self, messages, tools=None, retries=3):
        payload = {"model": self.model, "messages": messages,
                   "temperature": self.temperature}
        if tools:
            payload["tools"] = tools
        data = json.dumps(payload).encode("utf-8")

        for attempt in range(retries):
            req = urllib.request.Request(
                self.base_url + "/chat/completions",
                data=data,
                headers={"Content-Type": "application/json",
                         "Authorization": "Bearer " + self.api_key},
            )
            try:
                with urllib.request.urlopen(req, timeout=600) as resp:
                    body = json.loads(resp.read().decode("utf-8"))
                return body["choices"][0]["message"]
            except urllib.error.HTTPError as exc:
                detail = exc.read().decode("utf-8", "replace")[:600]
                if exc.code in (429, 500, 502, 503) and attempt < retries - 1:
                    wait = 2 ** attempt
                    self.log("[LLM busy (%d); retrying in %ds]" % (exc.code, wait))
                    time.sleep(wait)
                    continue
                raise RuntimeError(
                    "LLM API HTTP %s for %s (%s): %s\nHint: %s"
                    % (exc.code, self.base_url, self.model, detail, self.hint))
            except urllib.error.URLError as exc:
                if attempt < retries - 1:
                    wait = 2 ** attempt
                    self.log("[cannot reach LLM (%s); retrying in %ds]" % (exc.reason, wait))
                    time.sleep(wait)
                    continue
                raise RuntimeError("Cannot reach the LLM at %s: %s\nHint: %s"
                                   % (self.base_url, exc.reason, self.hint))


def chat_with_fallback(llms, messages, tools, log=print):
    """Try LLM clients in order; return (message, index_used)."""
    last = None
    for i, llm in enumerate(llms):
        try:
            return llm.chat(messages, tools), i
        except RuntimeError as exc:
            last = exc
            log("[provider '%s' failed: %s]" % (llm.provider, str(exc).splitlines()[0]))
            if i < len(llms) - 1:
                nxt = llms[i + 1]
                log("[falling back to '%s' (%s)]" % (nxt.provider, nxt.model))
    raise last


