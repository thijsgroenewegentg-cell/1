    @staticmethod
    def _extract_python(text: str, require_class: bool = True) -> str:
        """Pull Python source out of an LLM response.

        Handles the awkward case where the file being rewritten itself contains
        triple backticks, which breaks naive fence matching.

        Args:
            text: The raw model response.
            require_class: Only accept blocks that define a class.

        Returns:
            The extracted source, or ``""`` when nothing usable was found.
        """
        raw = text or ""
        blocks = extract_code_blocks(raw)
        for language, code in blocks:
            if language in ("", "python", "py") and (not require_class or "class" in code):
                return code.strip()

        # Unbalanced or nested fences: take everything after the first opening
        # fence and drop a trailing one.
        match = re.search(r"```(?:python|py)?[ \t]*\n", raw)
        if match:
            body = raw[match.end():]
            body = re.sub(r"\n```[\s\S]*$", "\n", body)
            if "def " in body or "class " in body:
                return body.strip()

        stripped = raw.strip()
        if stripped.startswith(("#", "from ", "import ", '"""')) and "def " in stripped:
            return stripped
        return ""

    def _validate_adapter(self, code: str, skill: str) -> Tuple[bool, str]:
        """Static safety and structure checks for generated plugin code."""
        if len(code) > self.max_file_bytes:
            return False, "generated file is implausibly large"
        try:
            tree = ast.parse(code)
        except SyntaxError as exc:
            return False, f"syntax error on line {exc.lineno}: {exc.msg}"

        banned = {
            "os.system", "subprocess.run", "subprocess.Popen", "subprocess.call",
            "shutil.rmtree", "eval", "exec", "compile", "__import__",
        }
        source = code.replace(" ", "")
        for pattern in banned:
            if pattern.replace(" ", "") + "(" in source:
                return False, f"generated code calls {pattern}, which I will not accept"

        has_class = any(
            isinstance(node, ast.ClassDef)
            and any(getattr(base, "id", getattr(base, "attr", "")) == "BaseModule"
                    for base in node.bases)
            for node in ast.walk(tree)
        )
        if not has_class:
            return False, "no BaseModule subclass found"
        if f'"{skill}"' not in code and f"'{skill}'" not in code:
            return False, f"the module does not set name = '{skill}'"
        if "@tool" not in code:
            return False, "no @tool methods were defined"
        return True, ""

    async def _register_plugin(self, skill: str, path: str) -> Dict[str, Any]:
        """Import a plugin file and register it with the running brain."""
        result: Dict[str, Any] = {"status": "written to disk", "tools": []}
        if not path:
            return result
        try:
            instance = await run_blocking(load_plugin, Path(path), self.config,
                                          self.llm, self.security)
            if instance is None:
                result["status"] = "written, but no BaseModule subclass could be imported"
                return result
            await instance.setup()
            result["tools"] = list(instance.tools)
            if self.brain is not None and hasattr(self.brain, "register_module"):
                self.brain.register_module(instance)
                result["status"] = "loaded and active right now"
            else:
                result["status"] = "loaded; active after restart"
        except Exception as exc:
            result["status"] = f"import failed ({truncate(str(exc), 160)}) — file kept for review"
        return result

