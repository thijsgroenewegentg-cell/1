def load_plugin(
    path: Path, config: Any, llm: Any = None, security: Any = None
) -> Optional[BaseModule]:
    """Import a plugin file and instantiate the first ``BaseModule`` subclass.

    Args:
        path: Path to a ``plugins/*.py`` file.
        config: The global configuration object.
        llm: Optional LLM client handed to the module.
        security: Optional security guard handed to the module.

    Returns:
        The instantiated module, or ``None`` when the file defines no module.
    """
    module_name = f"jarvis_plugin_{path.stem}"
    spec = importlib.util.spec_from_file_location(module_name, path)
    if spec is None or spec.loader is None:
        return None
    imported = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = imported
    spec.loader.exec_module(imported)

    for attribute in vars(imported).values():
        if (
            isinstance(attribute, type)
            and issubclass(attribute, BaseModule)
            and attribute is not BaseModule
            and attribute.__module__ == module_name
        ):
            return attribute(config, llm=llm, security=security)
    return None


def discover_plugins(directory: Path) -> List[Path]:
    """List loadable plugin files in ``directory``.

    Args:
        directory: The plugins folder.

    Returns:
        Sorted paths of candidate plugin modules.
    """
    if not directory.exists():
        return []
    return sorted(
        path
        for path in directory.glob("*.py")
        if not path.name.startswith("_") and path.name != "base.py"
    )


