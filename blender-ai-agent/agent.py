def run_task(task, bridge, llms, vision=False, max_iters=30, approve=False,
             reference_image=None, log=print):
    """Run one user request. `llms` is a list of LLMClient (fallback chain)."""
    if isinstance(llms, LLMClient):
        llms = [llms]
    tools = build_tools(vision)

    user_content = task
    if reference_image:
        log("[attaching reference image: %s]" % reference_image)
        user_content = [
            {"type": "text",
             "text": task + "\n\n(The attached image is a reference for what "
                            "I want. Build something based on it.)"},
            {"type": "image_url",
             "image_url": {"url": encode_reference_image(reference_image)}},
        ]

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]

    for step in range(1, max_iters + 1):
        log("\n[step %d] thinking..." % step)
        message, used = chat_with_fallback(llms, messages, tools, log=log)
        messages.append(message)

        tool_calls = message.get("tool_calls") or []
        content = (message.get("content") or "").strip()
        if content:
            log("AI: " + content)

        if not tool_calls:
            log("\n(The model finished without calling task_complete.)")
            return content or "Task finished."

        done_summary = None
        for call in tool_calls:
            fn = call.get("function", {})
            name = fn.get("name", "")
            args = _repair_json(fn.get("arguments") or "{}")

            if name == "task_complete":
                done_summary = args.get("summary", "Task complete.")
                messages.append({"role": "tool", "tool_call_id": call.get("id", "0"),
                                 "content": "Task marked complete."})
                continue

            try:
                tool_text, extra = dispatch_tool(
                    name, args, bridge, vision=vision, log=log, approve=approve)
            except KeyboardInterrupt:
                return "Stopped by user during approval."
            except (ConnectionError, OSError) as exc:
                raise RuntimeError(
                    "Lost connection to Blender: %s\nMake sure the bridge is "
                    "running (add-on panel > Start, or blender --python "
                    "bridge_standalone.py)." % exc)

            messages.append({"role": "tool", "tool_call_id": call.get("id", "0"),
                             "content": tool_text if tool_text is not None else "done"})
            # Vision results arrive as a follow-up user message containing the image.
            messages.extend(extra)

        if done_summary is not None:
            log("\n=== Done: %s ===" % done_summary)
            log("[files written to: %s]" % DEFAULT_OUT_DIR)
            return done_summary

    log("\n[reached max iterations (%d); stopping]" % max_iters)
    return "Stopped after %d steps." % max_iters


