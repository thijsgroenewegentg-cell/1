def _ask_approval(code, log):
    print("\n--- Agent wants to run this Blender code ---")
    print(code)
    print("-------------------------------------------")
    try:
        answer = input("Approve? [Enter=run, s=skip, q=quit] ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        return "run"
    if answer in ("q", "quit"):
        return "quit"
    if answer in ("s", "skip", "n", "no"):
        return "skip"
    return "run"


def dispatch_tool(name, args, bridge, vision=False, log=print, approve=False):
    """Run one tool call against Blender.

    Returns (content_text, extra_messages):
      content_text   -> string for the ordinary tool-role reply
      extra_messages -> extra messages to append (e.g. vision images)
    """
    if name == "get_scene_info":
        reply = bridge.call("scene_info")
        if not reply.get("ok"):
            return "ERROR: " + reply.get("error", "unknown error"), []
        return json.dumps(reply["result"], indent=2), []

    if name == "execute_blender_code":
        code = args.get("code", "")
        log("\n--- Blender code ---")
        for line in code.strip().splitlines():
            log("  " + line)
        log("--------------------")
        if approve:
            decision = _ask_approval(code, log)
            if decision == "quit":
                raise KeyboardInterrupt
            if decision == "skip":
                return "Skipped by the user. Try a different approach.", []
        reply = bridge.call("exec", code=code)
        if not reply.get("ok"):
            return "ERROR: " + reply.get("error", "unknown error"), []
        result = reply.get("result") or {}
        parts = []
        if result.get("stdout", "").strip():
            parts.append("stdout:\n" + result["stdout"].strip())
        if result.get("error"):
            parts.append("Python error (read the traceback and fix your code):\n"
                         + result["error"])
        if not parts:
            return "Code executed successfully with no output.", []
        return _truncate("\n\n".join(parts)), []

    if name in ("render_preview", "render_and_inspect"):
        path = args.get("filepath") or _timestamped("render", "png")
        note = args.get("note", "")
        log("\n[rendering preview -> %s ...]" % path)
        reply = bridge.call("render", filepath=path)
        if not reply.get("ok"):
            return "ERROR: " + reply.get("error", "unknown error"), []
        result = reply.get("result") or {}
        if result.get("error"):
            return "Render failed:\n" + result["error"], []
        out_path = result.get("filepath", path)
        log("[render saved: %s]" % out_path)

        text = ("Render saved to: %s%s"
                % (out_path, (" Note from you: " + note) if note else ""))
        extra = []
        if name == "render_and_inspect":
            if not vision:
                text += (" (Image attached below for analysis. If you cannot "
                         "see images, use render_preview instead.)")
            try:
                uri = _read_image_data_uri(out_path)
                extra.append({
                    "role": "user",
                    "content": [
                        {"type": "text",
                         "text": "This is the render of your current Blender "
                                 "scene. Inspect it carefully for problems "
                                 "(floating/intersecting objects, wrong colors, "
                                 "bad camera framing, missing parts) and fix any "
                                 "issues you see with execute_blender_code."
                                 + ((" Focus: " + note) if note else "")},
                        {"type": "image_url", "image_url": {"url": uri}},
                    ],
                })
            except Exception as exc:
                text += "\n(Warning: could not attach image: %s)" % exc
        return text, extra

    if name == "save_blend":
        path = args.get("filepath") or _timestamped("scene", "blend")
        if not path.lower().endswith(".blend"):
            path += ".blend"
        log("[saving .blend -> %s]" % path)
        reply = bridge.call("save", filepath=path)
        if not reply.get("ok"):
            return "ERROR: " + reply.get("error", "unknown error"), []
        result = reply.get("result") or {}
        if result.get("error"):
            return "Save failed:\n" + result["error"], []
        return "Saved Blender file to: %s" % result.get("filepath", path), []

    if name == "export_model":
        fmt = (args.get("format") or "").upper()
        path = args.get("filepath") or _timestamped("export", fmt.lower())
        log("[exporting %s -> %s]" % (fmt, path))
        reply = bridge.call("export", filepath=path, format=fmt)
        if not reply.get("ok"):
            return "ERROR: " + reply.get("error", "unknown error"), []
        result = reply.get("result") or {}
        if result.get("error"):
            return "Export failed:\n" + result["error"], []
        return "Exported %s to: %s" % (fmt, result.get("filepath", path)), []

    if name == "undo_blender":
        reply = bridge.call("undo")
        result = reply.get("result") or {}
        if result.get("error") or not reply.get("ok"):
            return "Undo failed: %s" % (result.get("error") or reply.get("error")), []
        return "Undid the last Blender step.", []

    if name == "task_complete":
        return None, []

    return "ERROR: unknown tool %r" % name, []


