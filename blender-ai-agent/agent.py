def _truncate(text):
    if text is None:
        return ""
    text = str(text)
    return text if len(text) <= MAX_OUTPUT_CHARS else text[:MAX_OUTPUT_CHARS] + "\n...[truncated]"


def _repair_json(raw):
    """Best-effort fix for model-emitted tool arguments that aren't valid JSON."""
    if isinstance(raw, dict):
        return raw
    if not raw:
        return {}
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        pass
    # Find the outermost { ... } block.
    match = re.search(r"\{.*\}", raw, re.DOTALL)
    candidate = match.group(0) if match else raw
    candidate = candidate.replace("\n", " ")
    # Common slip: Python-style True/False/None or single quotes around keys.
    try:
        return json.loads(candidate)
    except json.JSONDecodeError:
        pass
    # Extract a string value for known scalar keys as a last resort
    # (handles trailing commas, single-quoted keys, trailing prose, ...).
    # Try double-quoted values first, then single-quoted.
    for key in ("code", "summary", "filepath", "format", "note"):
        m = re.search(r"['\"]?%s['\"]?\s*:\s*\"(.*)\"\s*[,})\]]*$" % key,
                      candidate, re.DOTALL)
        if not m:
            m = re.search(r"['\"]?%s['\"]?\s*:\s*'(.*)'\s*[,})\]]*$" % key,
                          candidate, re.DOTALL)
        if m:
            value = m.group(1)
            try:
                return {key: json.loads('"%s"' % value)}
            except json.JSONDecodeError:
                return {key: value}
    return {}


def _ensure_out_dir():
    os.makedirs(DEFAULT_OUT_DIR, exist_ok=True)
    return DEFAULT_OUT_DIR


def _timestamped(prefix, ext):
    _ensure_out_dir()
    stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    return os.path.join(DEFAULT_OUT_DIR, "%s_%s.%s" % (prefix, stamp, ext))


def _read_image_data_uri(path):
    with open(path, "rb") as fh:
        b64 = base64.b64encode(fh.read()).decode("ascii")
    return "data:image/png;base64," + b64


def encode_reference_image(path):
    """Load a user-provided reference image as a data URI."""
    ext = os.path.splitext(path)[1].lower().lstrip(".")
    mime = {"jpg": "jpeg", "jpeg": "jpeg", "png": "png",
            "webp": "webp", "gif": "gif"}.get(ext, "png")
    with open(path, "rb") as fh:
        b64 = base64.b64encode(fh.read()).decode("ascii")
    return "data:image/%s;base64,%s" % (mime, b64)


