# --------------------------------------------------------------------------
# Blender bridge client
# --------------------------------------------------------------------------

class BlenderBridge:
    """JSON-lines client for the addon.py socket server."""

    def __init__(self, host=DEFAULT_HOST, port=DEFAULT_PORT, timeout=120):
        self.host = host
        self.port = port
        self.sock = socket.create_connection((host, port), timeout=10)
        self.sock.settimeout(timeout)
        self._buf = b""
        self._id = 0

    def call(self, cmd, **args):
        self._id += 1
        request = {"id": self._id, "cmd": cmd, "args": args}
        self.sock.sendall((json.dumps(request) + "\n").encode("utf-8"))
        while True:
            line = self._readline()
            reply = json.loads(line.decode("utf-8"))
            if reply.get("id") == self._id:
                return reply

    def _readline(self):
        while b"\n" not in self._buf:
            chunk = self.sock.recv(65536)
            if not chunk:
                raise ConnectionError("Blender closed the connection")
            self._buf += chunk
        line, self._buf = self._buf.split(b"\n", 1)
        return line

    def close(self):
        try:
            self.sock.close()
        except OSError:
            pass


