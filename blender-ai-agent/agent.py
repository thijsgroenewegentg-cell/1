# LLM client (OpenAI-compatible; works with Ollama, Groq, Gemini, OpenAI)
# --------------------------------------------------------------------------

class LLMClient:
    def __init__(self, provider="ollama", model=None, base_url=None,
                 api_key=None, temperature=0.2):
        if provider not in PROVIDERS:
            raise ValueError("Unknown provider %r. Choose from: %s"
                             % (provider, ", ".join(PROVIDERS)))
        cfg = PROVIDERS[provider]
        self.provider = provider
        self.base_url = (base_url or cfg["base_url"]).rstrip("/")
        self.model = model or cfg["model"]
        key = api_key
        if not key and cfg.get("key_env"):
            key = os.environ.get(cfg["key_env"], "")
        self.api_key = key or cfg.get("api_key", "")
        self.temperature = temperature
        self.hint = cfg.get("hint", "")

    def chat(self, messages, tools=None):
        payload = {
            "model": self.model,
            "messages": messages,
            "temperature": self.temperature,
        }
        if tools:
            payload["tools"] = tools
        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            self.base_url + "/chat/completions",
            data=data,
            headers={
                "Content-Type": "application/json",
                "Authorization": "Bearer " + self.api_key,
            },
        )
        try:
            with urllib.request.urlopen(req, timeout=600) as resp:
                body = json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            detail = exc.read().decode("utf-8", "replace")[:800]
            raise RuntimeError(
                "LLM API returned HTTP %s for %s (%s). Response: %s\nHint: %s"
                % (exc.code, self.base_url, self.model, detail, self.hint))
        except urllib.error.URLError as exc:
            raise RuntimeError(
                "Cannot reach the LLM at %s: %s\nHint: %s"
                % (self.base_url, exc.reason, self.hint))
        return body["choices"][0]["message"]


