# /modules/self_improve.py
"""Self-extension and self-modification.

This is the module that lets JARVIS grow:

* **Search GitHub** for repositories that do something he cannot yet do
  (the public search API needs no key — a ``GITHUB_TOKEN`` only raises the
  rate limit).
* **Integrate a repository** by cloning it into ``data/repos`` and having the
  local LLM write a JARVIS *adapter* — a real ``BaseModule`` with ``@tool``
  methods — into ``plugins/``. The adapter is compiled, imported, instantiated
  and registered live, so the new skill is usable in the same conversation and
  again after a restart.
* **Rewrite his own source code**: read a file, describe the change, get a
  unified diff, and apply it behind a safety net — backup, syntax check, test
  suite, hot reload, git commit, and automatic rollback if anything fails.

Safety is deliberately conservative: code edits and plugin installs are
``dangerous`` tools (so they route through :class:`utils.security.SecurityGuard`
confirmation), ``self_improve.protected`` files can never be rewritten, pip
installs are off until you enable them, and every accepted change is recorded
in SQLite with a restorable backup.
"""

