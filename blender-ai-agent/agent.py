def _truncate(text):
    if text is None:
        return ""
    text = str(text)
    if len(text) > MAX_OUTPUT_CHARS:
        return text[:MAX_OUTPUT_CHARS] + "\n...[truncated]"
    return text


def _dispatch_tool(name, args, bridge, log=print):
    """Run one tool call against Blender; return string content for the LLM."""
    if name == "get_scene_info":
        reply = bridge.call("scene_info")
        if not reply.get("ok"):
            return "ERROR: " + reply.get("error", "unknown error")
        return json.dumps(reply["result"], indent=2)

    if name == "execute_blender_code":
        code = args.get("code", "")
        log("\n--- Blender code ---")
        for line in code.strip().splitlines():
            log("  " + line)
        log("--------------------")
        reply = bridge.call("exec", code=code)
        if not reply.get("ok"):
            return "ERROR: " + reply.get("error", "unknown error")
        result = reply.get("result") or {}
        parts = []
        if result.get("stdout", "").strip():
            parts.append("stdout:\n" + result["stdout"].strip())
        if result.get("error"):
            parts.append("Python error (fix your code):\n" + result["error"])
        if not parts:
            return "Code executed successfully with no output."
        return _truncate("\n\n".join(parts))

    if name == "render_preview":
        log("\n[rendering preview...]")
        kwargs = {}
        if args.get("filepath"):
            kwargs["filepath"] = args["filepath"]
        reply = bridge.call("render", **kwargs)
        if not reply.get("ok"):
            return "ERROR: " + reply.get("error", "unknown error")
        result = reply.get("result") or {}
        if result.get("error"):
            return "Render failed:\n" + result["error"]
        log("[render saved to: %s]" % result.get("filepath"))
        return "Render saved to: %s (tell the user to open this file)." % result.get("filepath")

    if name == "task_complete":
        return None  # handled by caller

    return "ERROR: unknown tool %r" % name


def run_task(task, bridge, llm, max_iters=30, log=print):
    """Run one user request to completion. Returns the completion summary."""
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": task},
    ]

    for step in range(1, max_iters + 1):
        log("\n[step %d] thinking..." % step)
        message = llm.chat(messages, TOOLS)
        messages.append(message)

        tool_calls = message.get("tool_calls") or []
        content = (message.get("content") or "").strip()
        if content:
            log("AI: " + content)

        if not tool_calls:
            log("\n(The model finished without calling task_complete.)")
            return content or "Task finished."

        done_summary = None
        for call in tool_calls:
            fn = call.get("function", {})
            name = fn.get("name", "")
            raw_args = fn.get("arguments") or "{}"
            try:
                args = json.loads(raw_args) if isinstance(raw_args, str) else raw_args
            except json.JSONDecodeError:
                args = {}

            if name == "task_complete":
                done_summary = args.get("summary", "Task complete.")
                tool_content = "Task marked complete."
            else:
                try:
                    tool_content = _dispatch_tool(name, args, bridge, log=log)
                except (ConnectionError, OSError) as exc:
                    raise RuntimeError(
                        "Lost connection to Blender: %s\nMake sure the server "
                        "is running in Blender (AI Agent tab > Start)." % exc)
            messages.append({
                "role": "tool",
                "tool_call_id": call.get("id", "0"),
                "content": tool_content if tool_content is not None else "done",
            })

        if done_summary is not None:
            log("\n=== Done: %s ===" % done_summary)
            return done_summary

    log("\n[reached max iterations (%d); stopping]" % max_iters)
    return "Stopped after %d steps." % max_iters


