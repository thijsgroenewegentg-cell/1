def _connect_with_help(host, port):
    try:
        bridge = BlenderBridge(host, port)
    except (ConnectionError, OSError) as exc:
        print("Could not connect to Blender at %s:%d (%s)." % (host, port, exc))
        print("Open Blender -> 3D Viewport -> press N -> 'AI Agent' tab -> "
              "'Start AI Agent Server', then retry.")
        sys.exit(1)
    reply = bridge.call("ping")
    if reply.get("ok"):
        info = reply["result"]
        print("Connected to Blender %s (scene: %s)."
              % (info.get("blender"), info.get("scene")))
    return bridge


def _run_exec_file(path, bridge):
    with open(path, "r", encoding="utf-8") as fh:
        code = fh.read()
    reply = bridge.call("exec", code=code)
    result = reply.get("result") or {}
    if result.get("stdout"):
        print(result["stdout"], end="")
    if result.get("error"):
        print(result["error"], file=sys.stderr)
        sys.exit(1)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Free AI agent that builds things in Blender.")
    parser.add_argument("task", nargs="?",
                        help="What you want built, e.g. \"a small windmill\". "
                             "If omitted, starts interactive chat mode.")
    parser.add_argument("--provider", default=os.environ.get("LLM_PROVIDER", "ollama"),
                        choices=sorted(PROVIDERS.keys()),
                        help="LLM provider (default: ollama - free, local).")
    parser.add_argument("--model", default=os.environ.get("LLM_MODEL"),
                        help="Override the model name.")
    parser.add_argument("--base-url", default=os.environ.get("LLM_BASE_URL"),
                        help="Override the API base URL (any OpenAI-compatible server).")
    parser.add_argument("--host", default=DEFAULT_HOST)
    parser.add_argument("--port", type=int, default=DEFAULT_PORT)
    parser.add_argument("--max-iters", type=int, default=30)
    parser.add_argument("--exec", metavar="FILE",
                        help="Skip the LLM: just run a .py file inside Blender.")
    args = parser.parse_args(argv)

    bridge = _connect_with_help(args.host, args.port)

    if args.exec:
        _run_exec_file(args.exec, bridge)
        return

    llm = LLMClient(provider=args.provider, model=args.model,
                    base_url=args.base_url)
    print("Using LLM: %s via %s (free: %s)"
          % (llm.model, llm.provider,
             "yes" if args.provider in ("ollama", "groq", "gemini") else "no"))

    try:
        if args.task:
            run_task(args.task, bridge, llm, max_iters=args.max_iters)
        else:
            print("\nInteractive mode. Describe what you want built. "
                  "Commands: /scene - show scene info, /undo - undo last step, "
                  "/quit - exit.\n")
            while True:
                try:
                    task = input("you > ").strip()
                except (EOFError, KeyboardInterrupt):
                    print()
                    break
                if not task:
                    continue
                if task in ("/quit", "/exit"):
                    break
                if task == "/scene":
                    reply = bridge.call("scene_info")
                    print(json.dumps(reply.get("result", reply), indent=2))
                    continue
                if task == "/undo":
                    print(bridge.call("undo"))
                    continue
                try:
                    run_task(task, bridge, llm, max_iters=args.max_iters)
                except RuntimeError as exc:
                    print("\n[agent error] %s" % exc)
    except RuntimeError as exc:
        print("\n[agent error] %s" % exc)
        if "ollama" in str(exc).lower() or "11434" in str(exc):
            print("\nOllama quick start:")
            print("  1. Download Ollama: https://ollama.com")
            print("  2. ollama pull qwen2.5-coder:7b")
            print("  3. Make sure Ollama is running, then try again.")
        sys.exit(1)
    finally:
        bridge.close()


if __name__ == "__main__":
    main()
